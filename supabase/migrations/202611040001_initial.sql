-- PostgreSQL baseline. Legacy drizzle/ migrations are SQLite history only.
CREATE SCHEMA multtek;
REVOKE ALL ON SCHEMA multtek FROM PUBLIC;
SET search_path TO multtek, pg_catalog;

CREATE TABLE "users" (
	"id" text PRIMARY KEY NOT NULL,
	"name" text NOT NULL,
	"username" text NOT NULL,
	"email" text NOT NULL,
	"cpf" text NOT NULL,
	"phone" text NOT NULL,
	"password" text NOT NULL,
	"role" text NOT NULL,
	"active" integer DEFAULT 1 NOT NULL CHECK ("active" IN (0,1)),
	"deleted" integer DEFAULT 0 NOT NULL CHECK ("deleted" IN (0,1)),
	"created" text NOT NULL
);

CREATE TABLE "settings" (
	"key" text PRIMARY KEY NOT NULL,
	"value" text NOT NULL
);

CREATE TABLE "attempts" (
	"key" text PRIMARY KEY NOT NULL,
	"count" integer NOT NULL,
	"expires" bigint NOT NULL
);

CREATE TABLE "clients" (
	"id" text PRIMARY KEY NOT NULL,
	"name" text NOT NULL,
	"uf" text NOT NULL,
	"city" text NOT NULL,
	"active" integer DEFAULT 1 NOT NULL CHECK ("active" IN (0,1)),
 "cnpj" text UNIQUE CHECK (cnpj IS NULL OR cnpj ~ '^[A-Z0-9]{12}[0-9]{2}$')
);

CREATE TABLE "stages" (
	"id" text PRIMARY KEY NOT NULL,
	"name" text NOT NULL,
	"color" text NOT NULL,
	"position" integer NOT NULL,
	"initial" integer DEFAULT 0 NOT NULL CHECK ("initial" IN (0,1)),
	"done" integer DEFAULT 0 NOT NULL CHECK ("done" IN (0,1))
);

CREATE TABLE "origins" (
	"id" text PRIMARY KEY NOT NULL,
	"name" text NOT NULL
);

CREATE TABLE "sessions" (
	"token" text PRIMARY KEY NOT NULL,
	"user_id" text NOT NULL,
	"expires" bigint NOT NULL,
	FOREIGN KEY ("user_id") REFERENCES "users"("id") ON UPDATE no action ON DELETE no action
);

CREATE TABLE "tasks" (
	"id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	"summary" text NOT NULL,
	"client_id" text NOT NULL,
	"origin_id" text NOT NULL,
	"stage_id" text NOT NULL,
	"creator_id" text NOT NULL,
	"assignee_id" text NOT NULL,
	"duration" integer,
	"created" text NOT NULL,
	"updated" text NOT NULL,
	"completed" text,
	"deleted" integer DEFAULT 0 NOT NULL CHECK ("deleted" IN (0,1)),
	"version" integer DEFAULT 1 NOT NULL,
	"mutation" text NOT NULL,
	FOREIGN KEY ("client_id") REFERENCES "clients"("id") ON UPDATE no action ON DELETE no action,
	FOREIGN KEY ("origin_id") REFERENCES "origins"("id") ON UPDATE no action ON DELETE no action,
	FOREIGN KEY ("stage_id") REFERENCES "stages"("id") ON UPDATE no action ON DELETE no action,
	FOREIGN KEY ("creator_id") REFERENCES "users"("id") ON UPDATE no action ON DELETE no action,
	FOREIGN KEY ("assignee_id") REFERENCES "users"("id") ON UPDATE no action ON DELETE no action
);

CREATE TABLE "history" (
	"id" text PRIMARY KEY NOT NULL,
	"task_id" integer NOT NULL,
	"actor_id" text NOT NULL,
	"event" text NOT NULL,
	"created" text NOT NULL,
	FOREIGN KEY ("task_id") REFERENCES "tasks"("id") ON UPDATE no action ON DELETE no action,
	FOREIGN KEY ("actor_id") REFERENCES "users"("id") ON UPDATE no action ON DELETE no action
);

CREATE TABLE "notifications" (
	"id" text PRIMARY KEY NOT NULL,
	"user_id" text NOT NULL,
	"task_id" integer NOT NULL,
	"message" text NOT NULL,
	"created" text NOT NULL,
	"read" integer DEFAULT 0 NOT NULL CHECK ("read" IN (0,1)),
	"attempts" integer DEFAULT 0 NOT NULL,
	"sent" integer DEFAULT 0 NOT NULL CHECK ("sent" IN (0,1)),
	"next_attempt" bigint DEFAULT 0 NOT NULL,
	FOREIGN KEY ("user_id") REFERENCES "users"("id") ON UPDATE no action ON DELETE no action,
	FOREIGN KEY ("task_id") REFERENCES "tasks"("id") ON UPDATE no action ON DELETE no action
);

CREATE TABLE "attachments" (
	"id" text PRIMARY KEY NOT NULL,
	"task_id" integer NOT NULL,
	"user_id" text NOT NULL,
	"name" text NOT NULL,
	"mime" text NOT NULL,
	"size" integer NOT NULL,
	"created" text NOT NULL,
	FOREIGN KEY ("task_id") REFERENCES "tasks"("id") ON UPDATE no action ON DELETE no action,
	FOREIGN KEY ("user_id") REFERENCES "users"("id") ON UPDATE no action ON DELETE no action
);

CREATE TABLE "subscriptions" (
	"id" text PRIMARY KEY NOT NULL,
	"user_id" text NOT NULL,
	"endpoint" text NOT NULL,
	"data" text NOT NULL,
	FOREIGN KEY ("user_id") REFERENCES "users"("id") ON UPDATE no action ON DELETE no action
);

CREATE UNIQUE INDEX "subscriptions_endpoint_unique" ON "subscriptions" ("endpoint");

CREATE UNIQUE INDEX "users_username_unique" ON "users" ("username");

CREATE UNIQUE INDEX "users_email_unique" ON "users" ("email");

CREATE UNIQUE INDEX "users_cpf_unique" ON "users" ("cpf");

CREATE INDEX tasks_stage_idx ON tasks(stage_id,deleted);

CREATE INDEX tasks_assignee_idx ON tasks(assignee_id,deleted);

CREATE INDEX notifications_recipient_idx ON notifications(user_id,created);

CREATE INDEX notifications_outbox_idx ON notifications(sent,next_attempt);

CREATE INDEX sessions_user_idx ON sessions(user_id);

CREATE INDEX history_task_idx ON history(task_id,created);

CREATE INDEX attachments_task_idx ON attachments(task_id);


CREATE FUNCTION multtek.guard_user() RETURNS trigger LANGUAGE plpgsql SET search_path=multtek,pg_catalog AS $$
BEGIN
 IF OLD.role='admin' AND OLD.active=1 AND OLD.deleted=0 AND (NEW.role<>'admin' OR NEW.active=0 OR NEW.deleted=1) AND (SELECT count(*) FROM users WHERE role='admin' AND active=1 AND deleted=0)<=1 THEN RAISE EXCEPTION 'last_admin'; END IF;
 IF (NEW.active=0 OR NEW.deleted=1) AND EXISTS(SELECT 1 FROM tasks t JOIN stages s ON s.id=t.stage_id WHERE t.assignee_id=OLD.id AND t.deleted=0 AND s.done=0) THEN RAISE EXCEPTION 'open_assignments'; END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER guard_user BEFORE UPDATE OF active,deleted,role ON users FOR EACH ROW EXECUTE FUNCTION guard_user();
CREATE FUNCTION multtek.guard_task() RETURNS trigger LANGUAGE plpgsql SET search_path=multtek,pg_catalog AS $$
BEGIN
 IF TG_OP='UPDATE' THEN
  IF OLD.creator_id<>NEW.creator_id THEN RAISE EXCEPTION 'immutable_creator'; END IF;
  IF OLD.assignee_id=NEW.assignee_id THEN RETURN NEW; END IF;
 END IF;
 IF NOT EXISTS(SELECT 1 FROM users WHERE id=NEW.assignee_id AND active=1 AND deleted=0) THEN RAISE EXCEPTION 'inactive_assignee'; END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER guard_task BEFORE INSERT OR UPDATE ON tasks FOR EACH ROW EXECUTE FUNCTION guard_task();
REVOKE ALL ON ALL TABLES IN SCHEMA multtek FROM PUBLIC;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA multtek FROM PUBLIC;
REVOKE ALL ON ALL FUNCTIONS IN SCHEMA multtek FROM PUBLIC;
-- API authorization is enforced by the Worker. Do not expose this schema in Data API.
RESET search_path;
