);
CREATE TABLE "sessions" (
	"token" text PRIMARY KEY NOT NULL,
	"user_id" text NOT NULL,
	"expires" bigint NOT NULL,
	FOREIGN KEY ("user_id") REFERENCES "users"("id") ON UPDATE no action ON DELETE no action
);
CREATE TABLE "tasks" (
	"id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	"summary" text NOT NULL,
	"client_id" text NOT NULL,
	"origin_id" text NOT NULL,
	"stage_id" text NOT NULL,
	"creator_id" text NOT NULL,
	"assignee_id" text NOT NULL,
	"duration" integer,
	"created" text NOT NULL,
	"updated" text NOT NULL,
	"completed" text,
	"deleted" integer DEFAULT 0 NOT NULL,
	"version" integer DEFAULT 1 NOT NULL,
	"mutation" text NOT NULL,
	FOREIGN KEY ("client_id") REFERENCES "clients"("id") ON UPDATE no action ON DELETE no action,
	FOREIGN KEY ("origin_id") REFERENCES "origins"("id") ON UPDATE no action ON DELETE no action,
	FOREIGN KEY ("stage_id") REFERENCES "stages"("id") ON UPDATE no action ON DELETE no action,
	FOREIGN KEY ("creator_id") REFERENCES "users"("id") ON UPDATE no action ON DELETE no action,
	FOREIGN KEY ("assignee_id") REFERENCES "users"("id") ON UPDATE no action ON DELETE no action
);
CREATE TABLE "history" (
	"id" text PRIMARY KEY NOT NULL,
	"task_id" integer NOT NULL,
	"actor_id" text NOT NULL,
	"event" text NOT NULL,
	"created" text NOT NULL,
	FOREIGN KEY ("task_id") REFERENCES "tasks"("id") ON UPDATE no action ON DELETE no action,
	FOREIGN KEY ("actor_id") REFERENCES "users"("id") ON UPDATE no action ON DELETE no action
);
CREATE TABLE "notifications" (
	"id" text PRIMARY KEY NOT NULL,
	"user_id" text NOT NULL,
	"task_id" integer NOT NULL,
	"message" text NOT NULL,
	"created" text NOT NULL,
	"read" integer DEFAULT 0 NOT NULL,
	"attempts" integer DEFAULT 0 NOT NULL,
	"sent" integer DEFAULT 0 NOT NULL,
	"next_attempt" bigint DEFAULT 0 NOT NULL,
	FOREIGN KEY ("user_id") REFERENCES "users"("id") ON UPDATE no action ON DELETE no action,
	FOREIGN KEY ("task_id") REFERENCES "tasks"("id") ON UPDATE no action ON DELETE no action
);
CREATE TABLE "attachments" (
	"id" text PRIMARY KEY NOT NULL,
	"task_id" integer NOT NULL,
	"user_id" text NOT NULL,
	"name" text NOT NULL,
	"mime" text NOT NULL,
	"size" integer NOT NULL,
	"created" text NOT NULL,
	FOREIGN KEY ("task_id") REFERENCES "tasks"("id") ON UPDATE no action ON DELETE no action,
	FOREIGN KEY ("user_id") REFERENCES "users"("id") ON UPDATE no action ON DELETE no action
);
CREATE TABLE "subscriptions" (
	"id" text PRIMARY KEY NOT NULL,
	"user_id" text NOT NULL,
	"endpoint" text NOT NULL,
	"data" text NOT NULL,
	FOREIGN KEY ("user_id") REFERENCES "users"("id") ON UPDATE no action ON DELETE no action
);
CREATE UNIQUE INDEX "subscriptions_endpoint_unique" ON "subscriptions" ("endpoint");
CREATE UNIQUE INDEX "users_username_unique" ON "users" ("username");
CREATE UNIQUE INDEX "users_email_unique" ON "users" ("email");
CREATE UNIQUE INDEX "users_cpf_unique" ON "users" ("cpf");

CREATE FUNCTION protect_users() RETURNS trigger LANGUAGE plpgsql SET search_path = multtek, pg_temp AS $$
BEGIN
  PERFORM pg_advisory_xact_lock(724851);
  IF OLD.role='admin' AND OLD.active=1 AND OLD.deleted=0
    AND (NEW.role<>'admin' OR NEW.active=0 OR NEW.deleted=1)
    AND (SELECT COUNT(*) FROM users WHERE role='admin' AND active=1 AND deleted=0)<=1
    THEN RAISE EXCEPTION 'last_admin'; END IF;
  IF (NEW.active=0 OR NEW.deleted=1) AND EXISTS(
    SELECT 1 FROM tasks t JOIN stages s ON s.id=t.stage_id WHERE t.assignee_id=OLD.id AND t.deleted=0 AND s.done=0)
    THEN RAISE EXCEPTION 'open_assignments'; END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER users_integrity BEFORE UPDATE OF active,deleted,role ON users FOR EACH ROW EXECUTE FUNCTION protect_users();
CREATE FUNCTION protect_tasks() RETURNS trigger LANGUAGE plpgsql SET search_path = multtek, pg_temp AS $$
BEGIN
  IF TG_OP='UPDATE' THEN
    IF OLD.creator_id<>NEW.creator_id THEN RAISE EXCEPTION 'immutable_creator'; END IF;
    IF OLD.assignee_id=NEW.assignee_id THEN RETURN NEW; END IF;
  END IF;
  PERFORM 1 FROM users WHERE id=NEW.assignee_id AND active=1 AND deleted=0 FOR SHARE;
  IF NOT FOUND THEN RAISE EXCEPTION 'inactive_assignee'; END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER tasks_integrity BEFORE INSERT OR UPDATE OF creator_id,assignee_id ON tasks FOR EACH ROW EXECUTE FUNCTION protect_tasks();
CREATE INDEX tasks_stage_idx ON tasks(stage_id,deleted);
CREATE INDEX tasks_assignee_idx ON tasks(assignee_id,deleted);
