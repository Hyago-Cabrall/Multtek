let columns=0;
for(const {name} of tables){
 const old=sqlite.prepare(`PRAGMA table_info("${name}")`).all().map(c=>c.name).sort();
 const current=(await pg.query('SELECT column_name FROM information_schema.columns WHERE table_schema=$1 AND table_name=$2',['multtek',name])).rows.map(c=>c.column_name).sort();
 assert.deepEqual(current,old,name);columns+=old.length;
}
