import { readFileSync, mkdirSync, writeFileSync } from 'node:fs';
// Translate the existing schema without changing IDs, flags or password formats.
const original = readFileSync('drizzle/0000_curvy_ezekiel_stane.sql', 'utf8');
const order = ['users','attempts','clients','settings','stages','origins','sessions','tasks','history','notifications','attachments','subscriptions'];
const tables = new Map([...original.matchAll(/CREATE TABLE `([^`]+)` \([\s\S]*?\n\);/g)].map(match => [match[1], match[0]]));
let migration = `-- Multtek: isolated server-only schema. Apply once, in a transaction.\nBEGIN;\nCREATE SCHEMA multtek;\nREVOKE ALL ON SCHEMA multtek FROM PUBLIC, anon, authenticated;\nSET LOCAL search_path = multtek, public;\n`;
for (const name of order) {
  let sql = tables.get(name).replaceAll('`', '"').replace('integer PRIMARY KEY AUTOINCREMENT NOT NULL', 'integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY');
  sql = sql.replace(/"(expires|next_attempt)" integer/g, '"$1" bigint');
  if (name === 'clients') sql = sql.replace('"city" text NOT NULL,', '"city" text NOT NULL,\n "cnpj" text UNIQUE,');
  migration += sql + '\n';
}
migration += [...original.matchAll(/CREATE UNIQUE INDEX[^;]+;/g)].map(match => match[0].replaceAll('`', '"')).join('\n') + '\n';
migration += `
CREATE FUNCTION protect_users() RETURNS trigger LANGUAGE plpgsql SET search_path = multtek, pg_temp AS $$
BEGIN
  PERFORM pg_advisory_xact_lock(724851);
  IF OLD.role='admin' AND OLD.active=1 AND OLD.deleted=0
    AND (NEW.role<>'admin' OR NEW.active=0 OR NEW.deleted=1)
    AND (SELECT COUNT(*) FROM users WHERE role='admin' AND active=1 AND deleted=0)<=1
    THEN RAISE EXCEPTION 'last_admin'; END IF;
  IF (NEW.active=0 OR NEW.deleted=1) AND EXISTS(
    SELECT 1 FROM tasks t JOIN stages s ON s.id=t.stage_id WHERE t.assignee_id=OLD.id AND t.deleted=0 AND s.done=0)
    THEN RAISE EXCEPTION 'open_assignments'; END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER users_integrity BEFORE UPDATE OF active,deleted,role ON users FOR EACH ROW EXECUTE FUNCTION protect_users();
CREATE FUNCTION protect_tasks() RETURNS trigger LANGUAGE plpgsql SET search_path = multtek, pg_temp AS $$
BEGIN
  IF TG_OP='UPDATE' THEN
    IF OLD.creator_id<>NEW.creator_id THEN RAISE EXCEPTION 'immutable_creator'; END IF;
    IF OLD.assignee_id=NEW.assignee_id THEN RETURN NEW; END IF;
  END IF;
  PERFORM 1 FROM users WHERE id=NEW.assignee_id AND active=1 AND deleted=0 FOR SHARE;
  IF NOT FOUND THEN RAISE EXCEPTION 'inactive_assignee'; END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER tasks_integrity BEFORE INSERT OR UPDATE OF creator_id,assignee_id ON tasks FOR EACH ROW EXECUTE FUNCTION protect_tasks();
`;
migration += readFileSync('drizzle/0001_integrity.sql','utf8').match(/CREATE INDEX[^;]+;/g).join('\n') + '\n';
for (const table of order) migration += `ALTER TABLE "${table}" ENABLE ROW LEVEL SECURITY;\nREVOKE ALL ON TABLE "${table}" FROM PUBLIC, anon, authenticated;\n`;
migration += 'REVOKE ALL ON ALL FUNCTIONS IN SCHEMA multtek FROM PUBLIC, anon, authenticated;\nREVOKE ALL ON ALL SEQUENCES IN SCHEMA multtek FROM PUBLIC, anon, authenticated;\nCOMMIT;\n';
mkdirSync('supabase/migrations', { recursive: true });
writeFileSync('supabase/migrations/202611050001_multtek.sql', migration);
